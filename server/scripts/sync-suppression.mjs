#!/usr/bin/env node
// Bundles the outreach do-not-contact lists into the deployment as
// api/_seed.js, so the server refuses those addresses and domains even before
// anything has been imported into Redis. Run before each deploy:
//
//   node scripts/sync-suppression.mjs            (reads D:\resume\outreach)
//   node scripts/sync-suppression.mjs <folder>   (any folder holding the two files)
//
// The files are _contacted-emails.json and _contacted-domains.json, each a JSON
// array of strings. The output is not served publicly; it is only imported by
// the sending code.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2] || join(here, '..', '..', '..', 'resume', 'outreach');
const load = (f) => {
  const v = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  if (!Array.isArray(v)) throw new Error(`${f} is not a JSON array`);
  return [...new Set(v.map((x) => String(x).trim().toLowerCase()).filter(Boolean))].sort();
};
const emails = load('_contacted-emails.json');
const domains = load('_contacted-domains.json');
writeFileSync(join(here, '..', 'api', '_seed.js'),
  `// Generated by scripts/sync-suppression.mjs on ${new Date().toISOString()}. Do not edit by hand.\n` +
  `// Addresses and domains already contacted; the server never emails them.\n` +
  `export const SEED_EMAILS = ${JSON.stringify(emails)};\n` +
  `export const SEED_DOMAINS = ${JSON.stringify(domains)};\n`);
console.log(`wrote api/_seed.js: ${emails.length} emails, ${domains.length} domains`);
