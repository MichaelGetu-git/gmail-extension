#!/usr/bin/env node
// Copies the built-in templates out of the extension's content.js into
// api/_defaults.js, so the dashboard serves exactly what the extension ships
// with until someone saves a change. Run after editing the defaults:
//
//   node scripts/sync-defaults.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '..', '..', 'content.js'), 'utf8');
const a = src.indexOf('const SEGMENTS = [');
const SEGMENTS = new Function(src.slice(a, src.indexOf('\n];', a) + 3) + '; return SEGMENTS;')();
const out = Object.fromEntries(SEGMENTS.map((s) => [s.id, { subject: s.subject, body: s.body }]));
writeFileSync(join(here, '..', 'api', '_defaults.js'),
  `// Generated by scripts/sync-defaults.mjs from the extension's content.js. Do not edit by hand.\n` +
  `export const DEFAULT_TEMPLATES = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote api/_defaults.js:', Object.keys(out).join(', '));
